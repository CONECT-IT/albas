  1. Introducción

La presente Política de Privacidad establece los criterios bajo los cuales la empresa (en adelante, “la Inmobiliaria”) realiza el tratamiento de datos personales conforme a la Ley N.º 29733 – Ley de Protección de Datos Personales y su Reglamento aprobado mediante D.S. N.º 003-2013-JUS.
El titular acepta esta política al proporcionar su información y autoriza su incorporación en el banco de datos administrado por la Inmobiliaria.

2. Datos personales recopilados

El sistema CRM recopila y trata únicamente los datos necesarios para la adecuada prestación de servicios inmobiliarios. Estos pueden incluir:

2.1. Datos de identificación

Nombres y apellidos

Documento de identidad (solo si es requerido posteriormente)

2.2. Datos de contacto

Número telefónico

Correo electrónico (si corresponde)

2.3. Datos de ubicación

Dirección de residencia o domicilio declarado

2.4. Datos vinculados al proceso de atención

Información relacionada al estado de consultas, visitas, trámites y necesidades del titular

Historial de comunicaciones y seguimiento comercial

3. Finalidades del tratamiento de datos

La Inmobiliaria utilizará los datos personales para las siguientes finalidades lícitas y autorizadas:

3.1. Gestión de consultas, solicitudes y procesos de atención inmobiliaria.
3.2. Contacto y comunicación con el titular para brindar información, coordinar visitas, tramitar documentación o resolver dudas.
3.3. Registro de interacciones en el sistema CRM para asegurar una adecuada atención.
3.4. Elaboración de reportes internos y análisis de desempeño comercial.
3.5. Cumplimiento de obligaciones legales o contractuales relacionadas con la actividad inmobiliaria.
3.6. Mejora continua de los servicios, procesos y calidad de atención.

Sin consentimiento adicional del titular, no se utilizarán los datos personales para finalidades ajenas a las mencionadas.

4. Base legal para el tratamiento

El tratamiento se sustenta en:

4.1. El consentimiento libre, previo, informado y expreso del titular.
4.2. La relación precontractual y contractual derivada de los servicios inmobiliarios.
4.3. El interés legítimo de la Inmobiliaria en optimizar sus procesos internos, sin vulnerar los derechos fundamentales del titular.
4.4. Las obligaciones legales que exija la normativa peruana.

5. Límites y restricciones en el uso de los datos

La Inmobiliaria garantiza que:

5.1. No comercializa, cede ni transfiere datos personales a terceros sin autorización del titular, salvo obligación legal.
5.2. No utilizará la información para fines publicitarios no relacionados al proceso inmobiliario.
5.3. Mantendrá acceso limitado a personal estrictamente autorizado.
5.4. Adoptará políticas de minimización de datos, recolectando solo lo esencial.
5.5. Mantendrá registros de acceso y modificación dentro del CRM para fines de auditoría y seguridad.

6. Conservación de los datos

Los datos personales serán conservados en el banco de datos de la Inmobiliaria solo durante el tiempo necesario para cumplir las finalidades descritas.
Concluido el plazo razonable, la información será eliminada o anonimizada, siguiendo los criterios establecidos en la Ley 29733.

7. Seguridad de la información

En cumplimiento del artículo 28 de la Ley N.º 29733, la Inmobiliaria aplica medidas de seguridad técnicas, organizativas y legales para garantizar la protección de los datos, tales como:

Control de acceso mediante credenciales individuales.

Almacenamiento seguro en servidores y bases de datos protegidas.

Cifrado o resguardo seguro de información relevante.

Auditorías internas y registro de actividades del sistema CRM.

Capacitación periódica del personal autorizado.

8. Derechos ARCO del titular

El titular de los datos personales puede ejercer los derechos:

8.1. Acceso: conocer la información registrada sobre él.
8.2. Rectificación: corregir datos inexactos o incompletos.
8.3. Cancelación: solicitar la eliminación de los datos cuando corresponda.
8.4. Oposición: oponerse al tratamiento para finalidades no esenciales.

Estas solicitudes se podrán realizar a través de los canales oficiales de la Inmobiliaria, los cuales serán atendidos dentro de los plazos establecidos por la normativa peruana.

9. Encargados del tratamiento y terceros autorizados

La Inmobiliaria podrá emplear proveedores de servicios tecnológicos, de soporte o mantenimiento que actúen como encargados de tratamiento, siempre bajo contrato y con estrictas cláusulas de confidencialidad.
Dichos terceros solo podrán usar los datos siguiendo las instrucciones de la Inmobiliaria y respetando la Ley 29733.

10. Transferencias nacionales e internacionales

En caso la Inmobiliaria requiera almacenar o procesar datos en servidores ubicados fuera del Perú, se garantizará que el país receptor cuente con niveles adecuados de protección o que existan cláusulas contractuales que aseguren un tratamiento conforme a la ley peruana.

11. Modificaciones de la Política de Privacidad

Esta Política de Privacidad puede ser actualizada para cumplir con cambios normativos o mejoras internas.
Cualquier modificación será publicada oportunamente, y el uso continuo del sistema implicará su aceptación.

12. Aceptación

El titular declara haber leído, comprendido y aceptado los términos de esta Política de Privacidad y otorga su consentimiento expreso para el tratamiento de sus datos conforme a la Ley N.º 29733 y su Reglamento.
